function n(
  id: string,
  kind: DiagramNode["kind"],
  label: string,
  x: number,
  y: number,
  description = "",
  systemId: string | null = null,
): DiagramNode {
  return { id, kind, label, description, position: { x, y }, systemId };
}

function e(
  id: string,
  source: string,
  target: string,
  label = "",
  dashed = false,
): DiagramEdge {
  return { id, source, target, label, dashed };
}

